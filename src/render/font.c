static const char *const MARKS[] = {
    [FONT_MARK_NONE] = NULL,
    [FONT_MARK_ACUTE] = "...#." "..#..",
    [FONT_MARK_GRAVE] = ".#..." "..#..",
    [FONT_MARK_CIRCUMFLEX] = "..#.." ".#.#.",
    [FONT_MARK_DIAERESIS] = ".#.#." ".....",
    [FONT_MARK_CEDILLA] = "..#.." ".##..",
};

u32 font_next_codepoint(const char **s) {
    const u8 *p = (const u8 *)*s;
    if (p[0] == 0) {
        return 0;
    }
    u32 len = 1, cp = p[0];
    if (p[0] >= 0xF8 || (p[0] >= 0x80 && p[0] < 0xC0)) {
        *s += 1; // not a valid first byte (a continuation byte on its own...)
        return 0xFFFD;
    }
    if (p[0] >= 0xF0) {
        len = 4;
        cp = p[0] & 0x07u;
    } else if (p[0] >= 0xE0) {
        len = 3;
        cp = p[0] & 0x0Fu;
    } else if (p[0] >= 0xC0) {
        len = 2;
        cp = p[0] & 0x1Fu;
    }
    for (u32 i = 1; i < len; i++) {
        if ((p[i] & 0xC0u) != 0x80u) { // truncated sequence (the end of the string included)
            *s += 1;
            return 0xFFFD;
        }
        cp = (cp << 6) | (p[i] & 0x3Fu);
    }
    *s += len;
    return cp;
}

static const char *plain(u32 cp) {
    if (cp >= 'a' && cp <= 'z') {
        cp -= 'a' - 'A';
    }
    for (usize i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); i++) {
        if (GLYPHS[i].codepoint == cp) {
            return GLYPHS[i].pixels;
        }
    }
    return NULL;
}

bool font_glyph(u32 codepoint, FontGlyph *out) {
    if (codepoint == 0x2019 || codepoint == 0x2018) { // typographic apostrophes
        codepoint = '\'';
    } else if (codepoint == 0xA0 || codepoint == 0x202F) { // non-breaking spaces (French punctuation)
        codepoint = ' ';
    }
    for (usize i = 0; i < sizeof(ACCENTS) / sizeof(ACCENTS[0]); i++) {
        if (codepoint == ACCENTS[i].codepoint || codepoint == ACCENTS[i].codepoint + 0x20u) {
            *out = (FontGlyph){plain((u32)ACCENTS[i].base), ACCENTS[i].mark};
            return true;
        }
    }
    const char *pixels = plain(codepoint);
    if (pixels) {
        *out = (FontGlyph){pixels, FONT_MARK_NONE};
        return true;
    }
    *out = (FontGlyph){plain(QUESTION_MARK), FONT_MARK_NONE};
    return false;
}

const char *font_mark_pixels(FontMark mark) {
    return (mark >= FONT_MARK_NONE && mark <= FONT_MARK_CEDILLA) ? MARKS[mark] : NULL;
}

i32 font_text_width(const char *text, i32 scale) {
    i32 n = 0;
    while (font_next_codepoint(&text) != 0) {
        n++;
    }
    return n == 0 ? 0 : (n * FONT_ADVANCE - 1) * scale;
}
